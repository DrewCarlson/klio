fun main() {
    val sb = StringBuilder()
    sb.append("hello")
    sb.append(' ')
    sb.append("world")
    sb.append(42)
    println(sb.toString())
    println(sb.length)
    println(sb[0])
    println(sb.isEmpty())
    println(sb.isNotEmpty())
    sb.insert(0, "X")
    println(sb.toString())
    sb.deleteAt(0)
    println(sb.toString())
    sb.reverse()
    println(sb.toString())
    sb.clear()
    println(sb.isEmpty())
    sb.appendLine("line1").appendLine("line2")
    print(sb.toString())
    val seeded = StringBuilder("abc")
    println(seeded.toString())
    println(seeded.length)
}
