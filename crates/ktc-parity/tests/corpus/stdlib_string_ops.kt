fun main() {
    val s = "hello world"
    println(s.substringBefore(" "))
    println(s.substringAfter(" "))
    println(s.substringBeforeLast("o"))
    println(s.substringAfterLast("o"))
    println(s.replaceFirst("l", "L"))
    println(s.replace("l", "L"))
    println("abc".padStart(6, '_'))
    println("abc".padEnd(6, '_'))
    println("xy".repeat(3))
    println("racecar".reversed())
    println("Hello".lowercase())
    println("hello".uppercase())
    println("  pad  ".trim())
    println("  pad  ".trimStart())
    println("  pad  ".trimEnd())
    println("abc".startsWith("ab"))
    println("abc".endsWith("bc"))
    println("abc".contains("b"))
    println("abc".indexOf("b"))
    println("abc".lastIndexOf("b"))
    println("a,b,c".split(","))
    println("line1\nline2\nline3".lines())
    println("123".toInt())
    println("xx".toIntOrNull())
    println("1.5".toDouble())
    println("nope".toDoubleOrNull())
    println("true".toBoolean())
    println("TrUe".toBoolean())
    println("yes".toBoolean())
    println("true".toBooleanStrictOrNull())
    println("nope".toBooleanStrictOrNull())
    println("".isBlank())
    println("  ".isBlank())
    println("x".isBlank())
    println("".isNotBlank())
    println("x".isNotBlank())
}
