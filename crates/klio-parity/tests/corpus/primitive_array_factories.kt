fun main() {
    val i = intArrayOf(1, 2, 3)
    println(i.size)
    println(i[2])
    val l = longArrayOf(10L, 20L)
    println(l[1])
    val d = doubleArrayOf(1.5, 2.5, 3.5)
    println(d[0] + d[2])
    val b = booleanArrayOf(true, false, true)
    println(b[1])
    val c = charArrayOf('a', 'b', 'c')
    println(c[2])
    val s = shortArrayOf(1, 2, 3)
    println(s[0])
    val by = byteArrayOf(1, 2, 3)
    println(by[1])
    val f = floatArrayOf(1.0f, 2.0f)
    println(f[1])
}
