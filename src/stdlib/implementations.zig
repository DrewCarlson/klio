test "table has no duplicate fqns" {
    var seen = std.StringHashMap(void).init(testing.allocator);
    defer seen.deinit();
    for (TABLE) |e| {
        const gop = try seen.getOrPut(e.fqn);
        try testing.expect(!gop.found_existing);
    }
}

test "lookup returns null for unknown" {
    try testing.expect(lookup("kotlin.foo.bar") == null);
}

test "lookup finds a registered intrinsic" {
    try testing.expect(lookup("kotlin.math.abs") != null);
    try testing.expect(lookup("kotlin.io.println") != null);
}

test "source declarations resolve exact host ABI symbols" {
    try testing.expectEqualStrings(
        "kotlin.io.println",
        declarationHostSymbol("kotlin.io.println", null, "println").?,
    );
    try testing.expectEqualStrings(
        "kotlin.String.nativeIndexOf",
        declarationHostSymbol("kotlin.text.missingNativeIndexOf", "String", "nativeIndexOf").?,
    );
    try testing.expectEqualStrings(
        "kotlin.CharSequence.repeat",
        declarationHostSymbol("kotlin.text.repeat", "CharSequence", "repeat").?,
    );
    try testing.expect(
        declarationHostSymbol("sample.repeat", "CharSequence", "repeat") == null,
    );
    try testing.expectEqualStrings(
        "kotlin.Double.Companion.fromBits",
        declarationHostSymbol("kotlin.missingFromBits", "Double.Companion", "fromBits").?,
    );
    try testing.expect(declarationHostSymbol("kotlin.missing", "T", "missing") == null);
}

test "integer member applicability rejects non-numeric overload arguments" {
    const numeric_args = [_]Value{.{ .Int = 2 }};
    try testing.expectEqual(true, applicable("kotlin.Int.or", &numeric_args).?);

    const text = try runtime.strInit(testing.allocator, "bits");
    defer text.deinit();
    const other_args = [_]Value{.{ .String = text }};
    try testing.expectEqual(false, applicable("kotlin.Int.or", &other_args).?);
    try testing.expect(applicable("kotlin.Int.compareTo", &numeric_args) == null);
}

test "param names round trip" {
    const names = lookupParamNames("kotlin.String.repeat").?;
    try testing.expectEqual(@as(usize, 1), names.len);
    try testing.expectEqualStrings("n", names[0]);
    try testing.expect(lookupParamNames("kotlin.math.abs") == null);
}

test "all fqns iterates the whole table" {
    var it = allFqns();
    var n: usize = 0;
    while (it.next()) |_| n += 1;
    try testing.expectEqual(COUNT, n);
}
