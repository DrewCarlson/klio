/// Index of the range containing `needle` (mirrors the Kotlin
/// `binarySearchRange`).
fn binarySearchRange(arr: []const i32, needle: i32) usize {
    var bottom: i64 = 0;
    var top: i64 = @as(i64, @intCast(arr.len)) - 1;
    var middle: i64 = -1;
    var value: i32 = 0;
    while (bottom <= top) {
        middle = @divTrunc(bottom + top, 2);
        value = arr[@intCast(middle)];
        if (needle > value) {
            bottom = middle + 1;
        } else if (needle == value) {
            return @intCast(middle);
        } else {
            top = middle - 1;
        }
    }
    const adj: i64 = if (needle < value) 1 else 0;
    const r = middle - adj;
    return @intCast(if (r < 0) 0 else r);
}

fn categoryValueFrom(code: i32, ch: i32) i32 {
    if (code < 0x20) return code;
    if (code < 0x400) {
        return if ((ch & 1) == 1) (code >> 5) else (code & 0x1f);
    }
    return switch (@mod(ch, 3)) {
        2 => code >> 10,
        1 => (code >> 5) & 0x1f,
        else => code & 0x1f,
    };
}

/// Unicode general category value (JVM `Character.getType` style codes) of a
/// code point; 0 (UNASSIGNED) for an undefined code point.
pub fn categoryValue(ch: i32) i32 {
    const index = binarySearchRange(&range_start, ch);
    const start = range_start[index];
    const code = range_category[index];
    const value = categoryValueFrom(code, ch - start);
    return if (value == 17) 0 else value;
}
