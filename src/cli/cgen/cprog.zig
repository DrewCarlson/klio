// The functions the host calls back

/// A function the runtime's module lets the host call: a compiled body, a
/// native, or a closure class's `invoke`.
const Callback = union(enum) {
    compiled: FuncId,
    native: NativeId,
    invoke: u32,
    /// A closure class's `equals`, `hashCode` or `toString`.
    closure: struct { cls: u32, which: ClosureMember },
};

const Dispatch = struct { cls: u32, slot: u32, entry: u32 };
const HostRaised = struct { fqn: []const u8, raised: ir.resolved.Raised };

const Callbacks = struct {
    entries: std.ArrayList(Callback) = .empty,
    dispatch: std.ArrayList(Dispatch) = .empty,
    /// One per `Raise`.
    fixed: [9]?ir.resolved.Raised = @splat(null),
    match_groups: ?ir.resolved.ClassCtor = null,
    by_fqn: std.ArrayList(HostRaised) = .empty,

    fn entryOf(self: *Callbacks, p: *Program, cb: Callback) Error!u32 {
        for (self.entries.items, 0..) |e, i| {
            if (std.meta.eql(e, cb)) return @intCast(i);
        }
        try self.entries.append(p.a, cb);
        return @intCast(self.entries.items.len - 1);
    }
};

/// What the host may call back into: each constructed class's
/// implementations of the well-known members natives call back through, a
/// closure class's `invoke`, the constructors of the exceptions the runtime
/// raises into a `catch` of the program, and of the base classes it builds.
fn collectCallbacks(p: *Program) Error!Callbacks {
    var cbs: Callbacks = .{};
    for (p.rc.constructed.items) |c| {
        for (p.r.well_known.values) |wk| {
            const slot = wk orelse continue;
            const t = p.rc.target(c, slot) orelse continue;
            const cb: Callback = if (p.nativeOf(t)) |n| .{ .native = n } else if (p.body(t) != null) .{ .compiled = t } else continue;
            try cbs.dispatch.append(p.a, .{ .cls = c.int(), .slot = slot.int(), .entry = try cbs.entryOf(p, cb) });
        }
        // An instance of a class implementing a function type is invoked
        // through its `invoke`.
        for (p.r.host_class.invoke_slot) |slot| {
            const t = p.rc.target(c, slot) orelse continue;
            const cb: Callback = if (p.nativeOf(t)) |n| .{ .native = n } else if (p.body(t) != null) .{ .compiled = t } else continue;
            try cbs.dispatch.append(p.a, .{ .cls = c.int(), .slot = slot.int(), .entry = try cbs.entryOf(p, cb) });
        }
    }
    for (p.closures.items) |cc| {
        const h = &p.r.host_class;
        const members = [_]struct { ?MethodSlotId, ClosureMember }{ .{ h.equals_slot, .equals }, .{ h.hash_code_slot, .hash }, .{ h.to_string_slot, .to_string } };
        for (members) |mm| {
            const slot = mm[0] orelse continue;
            try cbs.dispatch.append(p.a, .{ .cls = cc.id, .slot = slot.int(), .entry = try cbs.entryOf(p, .{ .closure = .{ .cls = cc.id, .which = mm[1] } }) });
        }
        if (cc.arity >= h.invoke_slot.len) continue;
        try cbs.dispatch.append(p.a, .{ .cls = cc.id, .slot = h.invoke_slot[cc.arity].int(), .entry = try cbs.entryOf(p, .{ .invoke = cc.arity }) });
    }
    const e = &p.r.exceptions;
    const fixed = [_]?ir.resolved.Raised{ e.null_pointer, e.class_cast, e.arithmetic, e.uninitialized_property, e.index_out_of_bounds, e.array_index_out_of_bounds, e.string_index_out_of_bounds, p.r.base.init_failed, p.r.base.no_class_def };
    for (fixed, 0..) |x, k| {
        const raised = x orelse continue;
        if (!isRaisable(p, raised)) continue;
        _ = try cbs.entryOf(p, .{ .compiled = raised.ctor });
        cbs.fixed[k] = raised;
    }
    if (p.match_groups) |mg| if (p.body(mg.ctor) != null) {
        _ = try cbs.entryOf(p, .{ .compiled = mg.ctor });
        cbs.match_groups = mg;
    };
    for (p.rc.raisable_hosts.items) |hr| {
        if (!isRaisable(p, hr.raised)) continue;
        _ = try cbs.entryOf(p, .{ .compiled = hr.raised.ctor });
        try cbs.by_fqn.append(p.a, .{ .fqn = hr.key, .raised = hr.raised });
    }
    return cbs;
}

fn isRaisable(p: *const Program, raised: ir.resolved.Raised) bool {
    for (p.rc.raisable.items) |x| {
        if (x.class == raised.class and x.ctor == raised.ctor) return p.body(raised.ctor) != null;
    }
    return false;
}

/// The C function each compiled callback runs through: its arguments
/// boxed, its throw caught and handed back.
fn writeCallbacks(p: *Program, w: *Writer, cbs: *const Callbacks) Error!void {
    for (cbs.entries.items, 0..) |cb, i| {
        switch (cb) {
            .native => continue,
            .compiled => |f| {
                const b = p.body(f).?;
                try w.print("/* {s} */\nstatic int32_t kw_{d}(const klio_value *a, uint32_t n, klio_value *out) {{\n  (void)a; (void)n;\n", .{ p.funcName(f), i });
                try writeGuard(w);
                var call: std.Io.Writer.Allocating = .init(p.a);
                try call.writer.print("kf_{d}(", .{f.int()});
                if (b.closure) try call.writer.writeAll("klio_nat_null()");
                for (b.sig.params, 0..) |pt, k| {
                    if (k != 0 or b.closure) try call.writer.writeAll(", ");
                    try ctype.writeConv(&call.writer, .object, pt, try std.fmt.allocPrint(p.a, "a[{d}]", .{k}));
                }
                try call.writer.writeAll(")");
                try w.writeAll("  *out = ");
                try ctype.writeBox(w, b.sig.ret, call.written());
                try w.writeAll(";\n  klio_try_pop(&t);\n  return 0;\n}\n");
            },
            .invoke => |arity| {
                try w.print("static int32_t kw_{d}(const klio_value *a, uint32_t n, klio_value *out) {{\n  (void)n;\n", .{i});
                try writeGuard(w);
                try w.print("  *out = kcall(a[0], a + 1, {d});\n  klio_try_pop(&t);\n  return 0;\n}}\n", .{arity});
            },
            .closure => |c| {
                try w.print("static int32_t kw_{d}(const klio_value *a, uint32_t n, klio_value *out) {{\n  (void)n;\n", .{i});
                try writeGuard(w);
                switch (c.which) {
                    .equals => try w.print("  *out = kclo_eq_{d}(a[0], a[1]);\n", .{c.cls}),
                    .hash => try w.print("  *out = kclo_hash_{d}(a[0]);\n", .{c.cls}),
                    .to_string => try w.print("  *out = kclo_str_{d}(a[0]);\n", .{c.cls}),
                }
                try w.writeAll("  klio_try_pop(&t);\n  return 0;\n}\n");
            },
        }
    }
    try w.writeAll("\n");
}

fn writeGuard(w: *Writer) Error!void {
    try w.writeAll("  klio_try t; klio_nat_frame *m = klio_nat_frame_mark(); klio_try_arm(&t);\n");
    try w.writeAll("  if (setjmp(t.jb) != 0) { klio_nat_frame_restore(m); klio_try_top = t.prev; *out = klio_in_flight; return 1; }\n");
}

