//! The C file of a native build, in the order a C compiler accepts it: the
//! runtime's declarations, the bodies, the dispatchers, the singletons, the
//! description of the program the runtime builds its module from, and
//! `main`.

const std = @import("std");
const ir = @import("ir");
const sema = @import("sema");

const ctype = @import("ctype.zig");
const program = @import("program.zig");
const cfunc = @import("cfunc.zig");
const sig_mod = @import("sig.zig");
const rt = @import("rt_abi.zig");

const Ty = ctype.Ty;
const Program = program.Program;
const Writer = std.Io.Writer;
const FuncId = ir.FuncId;
const ClassId = ir.ClassId;
const NativeId = ir.NativeId;
const MethodSlotId = ir.MethodSlotId;
const Error = cfunc.Error;
const Raise = rt.Raise;
const NONE = ir.resolved.NONE;

pub fn write(p: *Program, w: *Writer, src_path: []const u8) Error!void {
    try w.print(
        \\/* Generated by `klio transpile --native {s}`. Do not edit.
        \\ * The program itself: every function is a C function over the klio
        \\ * runtime's values; no image is loaded and no interpreter runs it.
        \\ * Build: zig cc -O2 <this file> -I<include> -L<lib> -lklio_rt -lzstd */
        \\#include <stdio.h>
        \\#include <stdint.h>
        \\#include <stdlib.h>
        \\#include <string.h>
        \\#include <math.h>
        \\#include <setjmp.h>
        \\#include <klio_rt.h>
        \\
        \\
    , .{src_path});
    var callbacks = try collectCallbacks(p);
    try writeMachinery(w);
    try writeDeclarations(p, w);
    try writeStorage(p, w);
    for (p.bodies.items) |*b| try cfunc.writeBody(p, w, b);
    try writeClosureMembers(p, w);
    try writeDispatchers(p, w);
    try writeCallValue(p, w);
    try writeSingletons(p, w);
    try writeCallbacks(p, w, &callbacks);
    try writeClasses(p, w);
    try writeProgram(p, w, &callbacks);
    try writeMain(p, w);
}

fn writeMachinery(w: *Writer) Error!void {
    try w.writeAll(
        \\/* A try region. `setjmp` has to be called in the frame that catches,
        \\ * so the handler stack lives here rather than in the runtime. */
        \\typedef struct klio_try { struct klio_try *prev; jmp_buf jb; } klio_try;
        \\static klio_try *klio_try_top = 0;
        \\static klio_value klio_in_flight;
        \\static void klio_try_arm(klio_try *t) { t->prev = klio_try_top; klio_try_top = t; }
        \\static void klio_try_pop(klio_try *t) {
        \\  for (klio_try *q = klio_try_top; q; q = q->prev) if (q == t) { klio_try_top = t->prev; return; }
        \\}
        \\/* An exception the runtime raises: built through the class the program
        \\ * registered for it and thrown into the program. */
        \\#define kraise klio_r_raise
        \\KLIO_NORETURN static void kthrow(klio_value e) {
        \\  if (klio_nat_is_null(e)) klio_r_raise(0u, klio_nat_null());
        \\  klio_in_flight = e;
        \\  if (klio_try_top) longjmp(klio_try_top->jb, 1);
        \\  klio_r_uncaught(e);
        \\}
        \\
        \\
    );
}

fn writeDeclarations(p: *Program, w: *Writer) Error!void {
    for (p.bodies.items) |*b| {
        try cfunc.writeProto(w, b);
        try w.writeAll(";\n");
    }
    for (p.rc.slots.items) |slot| try writeDispatcherProto(p, w, slot);
    try w.writeAll("static klio_value kcall(klio_value f, const klio_value *a, uint32_t n);\n");
    for (p.objects.items) |c| try w.print("static klio_value ko_{d}(void);\n", .{c.int()});
    for (p.units.items, 0..) |_, i| try w.print("static void ku_{d}(void);\n", .{i});
    for (p.closures.items) |cc| if (cc.kind == .lambda and cc.n_caps == 0) try w.print("static klio_value klam_{d}(void);\n", .{cc.id});
    try w.writeAll("\n");
}

fn writeDispatcherProto(p: *Program, w: *Writer, slot: MethodSlotId) Error!void {
    const sg = try p.sigs.of(FuncId.from(slot.int()));
    try w.print("static {s} kv_{d}(", .{ sg.ret.cName(), slot.int() });
    for (sg.params, 0..) |t, i| {
        if (i != 0) try w.writeAll(", ");
        try w.print("{s} a{d}", .{ t.cName(), i });
    }
    if (sg.params.len == 0) try w.writeAll("void");
    try w.writeAll(");\n");
}

/// Statics, init-unit states, singletons and non-capturing closures, in a
/// frame published for the program's life.
fn writeStorage(p: *Program, w: *Writer) Error!void {
    const n_roots = p.statics.items.len + p.objects.items.len + p.closures.items.len + 2;
    try w.print("static klio_value KROOT[{d}];\nstatic klio_nat_frame KROOTF;\n", .{n_roots});
    try w.print("#define KG (KROOT + 2)\n#define KO (KROOT + {d})\n#define KL (KROOT + {d})\n", .{ 2 + p.statics.items.len, 2 + p.statics.items.len + p.objects.items.len });
    if (p.units.items.len != 0) try w.print("static uint8_t KU[{d}];\n", .{p.units.items.len});
    if (p.objects.items.len != 0) try w.print("static uint8_t KOS[{d}];\n", .{p.objects.items.len});
    try w.writeAll("\n");
}

/// Which `Any` member of a closure a slot is.
const ClosureMember = enum { equals, hash, to_string };

fn closureMemberOf(p: *const Program, slot: MethodSlotId) ?ClosureMember {
    const h = &p.r.host_class;
    if (h.equals_slot) |s| if (s == slot) return .equals;
    if (h.hash_code_slot) |s| if (s == slot) return .hash;
    if (h.to_string_slot) |s| if (s == slot) return .to_string;
    return null;
}

/// A closure answers `equals`, `hashCode` and `toString` by what it is, as
/// the VM's closures do: a reference by its target and its bound receiver,
/// a lambda by identity, and its text as kotlinc prints it.
fn writeClosureMembers(p: *Program, w: *Writer) Error!void {
    for (p.closures.items) |cc| {
        const func = p.m.funcById(cc.body) orelse continue;
        const kind: ir.resolved.Callable = if (cc.kind == .function_ref) .{ .function_ref = cc.target } else .lambda;
        const text = try ir.eval.resolved_ops.closureText(p.a, p.m, .{ .id = 0, .func = func, .module = p.m, .kind = kind });
        try w.print("static klio_value kclo_eq_{d}(klio_value self, klio_value other) {{\n", .{cc.id});
        try w.print("  if (klio_nat_bool(klio_r_binop({d}u, self, other))) return klio_nat_box_bool(1);\n", .{@intFromEnum(ir.BinOp.IdentEq)});
        if (cc.kind == .function_ref) {
            // One adapter per target and shape, so one class is one callable.
            try w.print("  if (klio_r_class_of(other) != {d}u) return klio_nat_box_bool(0);\n", .{cc.id});
            var i: u32 = 0;
            while (i < cc.n_caps) : (i += 1) {
                try w.print("  if (!klio_r_equals(klio_r_get(self, {d}), klio_r_get(other, {d}))) return klio_nat_box_bool(0);\n", .{ i, i });
            }
            try w.writeAll("  return klio_nat_box_bool(1);\n}\n");
            try w.print("static klio_value kclo_hash_{d}(klio_value self) {{\n  uint32_t h = {d}u;\n", .{ cc.id, cc.target.int() & 0x7fffffff });
            i = 0;
            while (i < cc.n_caps) : (i += 1) try w.print("  h = h * 31u + (uint32_t)klio_r_hash_code(klio_r_get(self, {d}));\n", .{i});
            try w.writeAll("  (void)self;\n  return klio_nat_box_int((int32_t)h);\n}\n");
            try w.print("static klio_value kclo_str_{d}(klio_value self) {{\n  (void)self;\n  return klio_nat_string(", .{cc.id});
            try ctype.writeCString(w, text);
            try w.print(", {d});\n}}\n", .{text.len});
        } else {
            try w.writeAll("  return klio_nat_box_bool(0);\n}\n");
            try w.print("static klio_value kclo_hash_{d}(klio_value self) {{\n  return klio_nat_box_int(klio_r_identity_hash(self));\n}}\n", .{cc.id});
            // A lambda's text ends in its instance's hash.
            const stem = if (std.mem.findScalarLast(u8, text, '@')) |at| text[0..at] else text;
            try w.print("static klio_value kclo_str_{d}(klio_value self) {{\n  return klio_r_lambda_text(", .{cc.id});
            try ctype.writeCString(w, stem);
            try w.writeAll(", self);\n}\n");
        }
    }
    if (p.closures.items.len != 0) try w.writeAll("\n");
}

/// A virtual call: the implementation of the receiver's class, converted
/// to and from the root's signature.
fn writeDispatchers(p: *Program, w: *Writer) Error!void {
    for (p.rc.slots.items) |slot| {
        const root_id = FuncId.from(slot.int());
        const sg = try p.sigs.of(root_id);
        try w.print("/* {s} */\n", .{p.funcName(root_id)});
        try w.print("static {s} kv_{d}(", .{ sg.ret.cName(), slot.int() });
        for (sg.params, 0..) |t, i| {
            if (i != 0) try w.writeAll(", ");
            try w.print("{s} a{d}", .{ t.cName(), i });
        }
        if (sg.params.len == 0) try w.writeAll("void");
        try w.writeAll(") {\n");
        if (sg.params.len == 0 or sg.params[0] != .object) {
            p.refuse("the slot `{s}` has no receiver", .{p.funcName(root_id)});
            try w.writeAll("  abort();\n}\n");
            continue;
        }
        try w.writeAll("  switch (klio_r_class_of(a0)) {\n");
        var classes: std.ArrayList(ClassId) = .empty;
        try classes.appendSlice(p.a, p.rc.constructed.items);
        try classes.appendSlice(p.a, p.rc.hosts.items);
        var done: std.AutoHashMapUnmanaged(u32, void) = .empty;
        for (classes.items) |c| {
            if (done.contains(c.int())) continue;
            const t = p.rc.target(c, slot) orelse continue;
            // Every class this target serves shares one arm.
            try w.print("  case {d}u:", .{c.int()});
            try done.put(p.a, c.int(), {});
            for (classes.items) |c2| {
                if (done.contains(c2.int())) continue;
                const t2 = p.rc.target(c2, slot) orelse continue;
                if (t2 != t) continue;
                try w.print(" case {d}u:", .{c2.int()});
                try done.put(p.a, c2.int(), {});
            }
            try w.writeAll("\n    return ");
            try writeTargetCall(p, w, t, sg, "a");
            try w.writeAll(";\n");
        }
        // A closure answers its own `invoke`.
        for (p.closures.items) |cc| {
            if (!isInvokeSlot(p, slot, cc.arity)) continue;
            try w.print("  case {d}u: {{ klio_value ka[{d}] = {{", .{ cc.id, @max(cc.arity, 1) });
            var i: u32 = 0;
            while (i < cc.arity) : (i += 1) {
                if (i != 0) try w.writeAll(", ");
                try ctype.writeBox(w, sg.params[i + 1], try std.fmt.allocPrint(p.a, "a{d}", .{i + 1}));
            }
            if (cc.arity == 0) try w.writeAll("{0}");
            try w.writeAll("};\n    return ");
            try ctype.writeConv(w, .object, sg.ret, try std.fmt.allocPrint(p.a, "kcall(a0, ka, {d})", .{cc.arity}));
            try w.writeAll("; }\n");
        }
        if (closureMemberOf(p, slot)) |which| for (p.closures.items) |cc| {
            try w.print("  case {d}u: return ", .{cc.id});
            const call = switch (which) {
                .equals => blk: {
                    var aw: std.Io.Writer.Allocating = .init(p.a);
                    try ctype.writeBox(&aw.writer, if (sg.params.len > 1) sg.params[1] else .object, "a1");
                    break :blk try std.fmt.allocPrint(p.a, "kclo_eq_{d}(a0, {s})", .{ cc.id, aw.written() });
                },
                .hash => try std.fmt.allocPrint(p.a, "kclo_hash_{d}(a0)", .{cc.id}),
                .to_string => try std.fmt.allocPrint(p.a, "kclo_str_{d}(a0)", .{cc.id}),
            };
            try ctype.writeConv(w, .object, sg.ret, call);
            try w.writeAll(";\n");
        };
        try w.writeAll("  default: break;\n  }\n");
        try w.print("  if (klio_nat_is_null(a0)) kraise({d}u, klio_nat_null());\n", .{@intFromEnum(Raise.npe)});
        // A host value whose class leaves the slot open: the VM's
        // implementation of the slot's root.
        if (slot.int() < p.r.host_slot.len and p.r.host_slot[slot.int()] != .none) {
            const hn = p.r.host_slot[slot.int()];
            try w.print("  {{ klio_value ka[{d}] = {{", .{sg.params.len});
            for (sg.params, 0..) |t, i| {
                if (i != 0) try w.writeAll(", ");
                try ctype.writeBox(w, t, try std.fmt.allocPrint(p.a, "a{d}", .{i}));
            }
            try w.writeAll("};\n    return ");
            const call = try std.fmt.allocPrint(p.a, "klio_r_native_call({d}u, ka, {d})", .{ p.nativeIndex(hn), sg.params.len });
            try ctype.writeConv(w, .object, sg.ret, call);
            try w.writeAll("; }\n}\n\n");
            continue;
        }
        try w.writeAll("  klio_r_no_method(");
        try ctype.writeCString(w, p.funcName(root_id));
        try w.writeAll(");\n}\n\n");
    }
}

/// Argument `i` of a dispatcher: `a<i>` for its parameters, `ab[<i>]` for
/// an array of them.
fn argName(p: *Program, prefix: []const u8, i: usize) Error![]const u8 {
    if (std.mem.endsWith(u8, prefix, "[")) return std.fmt.allocPrint(p.a, "{s}{d}]", .{ prefix, i });
    return std.fmt.allocPrint(p.a, "{s}{d}", .{ prefix, i });
}

fn isInvokeSlot(p: *const Program, slot: MethodSlotId, arity: u32) bool {
    const h = &p.r.host_class;
    if (arity < h.invoke_slot.len and h.invoke_slot[arity] == slot) return true;
    if (arity < h.suspend_invoke_slot.len and h.suspend_invoke_slot[arity] == slot) return true;
    return false;
}

/// A call of target `t` from a dispatcher whose parameters `<prefix>i`
/// have the kinds `sg` gives, as an expression of `sg.ret`.
fn writeTargetCall(p: *Program, w: *Writer, t: FuncId, sg: sig_mod.Sig, prefix: []const u8) Error!void {
    if (p.nativeOf(t)) |n| {
        var call: std.Io.Writer.Allocating = .init(p.a);
        try call.writer.print("klio_r_native_call({d}u, (klio_value[]){{", .{p.nativeIndex(n)});
        for (sg.params, 0..) |pt, i| {
            if (i != 0) try call.writer.writeAll(", ");
            try ctype.writeBox(&call.writer, pt, try argName(p, prefix, i));
        }
        if (sg.params.len == 0) try call.writer.writeAll("{0}");
        try call.writer.print("}}, {d})", .{sg.params.len});
        try ctype.writeConv(w, .object, sg.ret, call.written());
        return;
    }
    const b = p.body(t) orelse {
        p.refuse("the implementation `{s}` is not compiled", .{p.funcName(t)});
        try w.writeAll("0");
        return;
    };
    if (b.sig.params.len != sg.params.len) {
        p.refuse("`{s}` takes {d} parameters where its root takes {d}", .{ p.funcName(t), b.sig.params.len, sg.params.len });
        try w.writeAll("0");
        return;
    }
    var call: std.Io.Writer.Allocating = .init(p.a);
    try call.writer.print("kf_{d}(", .{t.int()});
    for (sg.params, b.sig.params, 0..) |have, want, i| {
        if (i != 0) try call.writer.writeAll(", ");
        try ctype.writeConv(&call.writer, have, want, try argName(p, prefix, i));
    }
    try call.writer.writeAll(")");
    try ctype.writeConv(w, b.sig.ret, sg.ret, call.written());
}

/// A signature with every parameter and the result boxed.
fn boxedSig(p: *Program, sg: sig_mod.Sig) Error!sig_mod.Sig {
    var out = sg;
    const ps = try p.a.alloc(Ty, sg.params.len);
    @memset(ps, .object);
    out.params = ps;
    out.ret = .object;
    return out;
}

/// Calling a function value: a closure's body, or the `invoke` of an
/// instance of a class implementing a function type.
fn writeCallValue(p: *Program, w: *Writer) Error!void {
    try w.writeAll("static klio_value kcall(klio_value f, const klio_value *a, uint32_t n) {\n  (void)a; (void)n;\n  switch (klio_r_class_of(f)) {\n");
    for (p.closures.items) |cc| {
        const b = p.body(cc.body) orelse continue;
        try w.print("  case {d}u: if (n == {d}) return ", .{ cc.id, cc.arity });
        var call: std.Io.Writer.Allocating = .init(p.a);
        try call.writer.print("kf_{d}(f", .{cc.body.int()});
        for (b.sig.params, 0..) |pt, i| {
            try call.writer.writeAll(", ");
            try ctype.writeConv(&call.writer, .object, pt, try std.fmt.allocPrint(p.a, "a[{d}]", .{i}));
        }
        try call.writer.writeAll(")");
        try ctype.writeBox(w, b.sig.ret, call.written());
        try w.writeAll("; break;\n");
    }
    // Instances of a class implementing `invoke` of a function type.
    const h = &p.r.host_class;
    for (p.rc.constructed.items) |c| {
        for (h.invoke_slot, 0..) |slot, arity| {
            const t = p.rc.target(c, slot) orelse continue;
            if (p.body(t) == null and p.nativeOf(t) == null) continue;
            try w.print("  case {d}u: if (n == {d}) {{\n", .{ c.int(), arity });
            const sg = try p.sigs.of(FuncId.from(slot.int()));
            var i: u32 = 0;
            try w.writeAll("    klio_value ab[] = {f");
            while (i < arity) : (i += 1) try w.print(", a[{d}]", .{i});
            try w.writeAll("};\n    (void)ab;\n    return ");
            try writeTargetCall(p, w, t, try boxedSig(p, sg), "ab[");
            try w.writeAll(";\n  }\n  break;\n");
            break;
        }
    }
    try w.print("  default: break;\n  }}\n  if (klio_nat_is_null(f)) kraise({d}u, klio_nat_null());\n  klio_r_no_method(\"invoke\");\n}}\n\n", .{@intFromEnum(Raise.npe)});
}

/// Objects and companions, made on first use; init units, run on the first
/// touch of a static they write; non-capturing closures, one instance each.
fn writeSingletons(p: *Program, w: *Writer) Error!void {
    for (p.objects.items, 0..) |c, i| {
        const ctor = p.r.classes[c.int()].object_ctor;
        try w.print("static klio_value ko_{d}(void) {{\n  static const char kname[] = ", .{c.int()});
        try ctype.writeCString(w, p.r.classes[c.int()].init_name);
        try w.print(";\n  if (KOS[{d}] == 1 || KOS[{d}] == 2) return KO[{d}];\n", .{ i, i, i });
        try w.print("  if (KOS[{d}] == 3) klio_r_init_failed(klio_nat_null(), kname);\n", .{i});
        try w.print("  KOS[{d}] = 1;\n  KO[{d}] = klio_r_new({d}u);\n", .{ i, i, c.int() });
        try w.writeAll("  { klio_try t; klio_nat_frame *m = klio_nat_frame_mark(); klio_try_arm(&t);\n");
        try w.print("    if (setjmp(t.jb) != 0) {{ klio_nat_frame_restore(m); klio_try_top = t.prev; KO[{d}] = klio_nat_null(); KOS[{d}] = 3; klio_r_init_failed(klio_in_flight, kname); }}\n", .{ i, i });
        if (ctor != ir.NO_FUNC) {
            const b = p.body(FuncId.from(ctor)) orelse {
                p.refuse("the object constructor `{s}` is not compiled", .{p.funcName(FuncId.from(ctor))});
                continue;
            };
            try w.print("    (void)kf_{d}(", .{ctor});
            try ctype.writeConv(w, .object, if (b.sig.params.len != 0) b.sig.params[0] else .object, try std.fmt.allocPrint(p.a, "KO[{d}]", .{i}));
            try w.writeAll(");\n");
        }
        try w.print("    klio_try_pop(&t); }}\n  KOS[{d}] = 2;\n  return KO[{d}];\n}}\n\n", .{ i, i });
    }
    for (p.units.items, 0..) |unit, i| {
        const f = p.r.init_units[unit].func;
        try w.print("static void ku_{d}(void) {{\n  static const char kname[] = ", .{i});
        try ctype.writeCString(w, p.r.init_units[unit].name);
        try w.print(";\n  if (KU[{d}] == 1 || KU[{d}] == 2) return;\n  if (KU[{d}] == 3) klio_r_init_failed(klio_nat_null(), kname);\n  KU[{d}] = 1;\n", .{ i, i, i, i });
        try w.writeAll("  { klio_try t; klio_nat_frame *m = klio_nat_frame_mark(); klio_try_arm(&t);\n");
        try w.print("    if (setjmp(t.jb) != 0) {{ klio_nat_frame_restore(m); klio_try_top = t.prev; KU[{d}] = 3; klio_r_init_failed(klio_in_flight, kname); }}\n", .{i});
        try w.print("    (void)kf_{d}();\n    klio_try_pop(&t); }}\n  KU[{d}] = 2;\n}}\n\n", .{ f.int(), i });
    }
    var li: usize = 0;
    for (p.closures.items) |cc| {
        if (cc.kind != .lambda or cc.n_caps != 0) continue;
        try w.print("static klio_value klam_{d}(void) {{\n  if (klio_nat_is_null(KL[{d}])) KL[{d}] = klio_r_new({d}u);\n  return KL[{d}];\n}}\n\n", .{ cc.id, li, li, cc.id, li });
        li += 1;
    }
}

