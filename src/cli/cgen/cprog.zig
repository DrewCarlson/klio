/// Every class the program registers: its layout, its ancestors, the flags
/// the host's rendering and equality read.
fn writeClasses(p: *Program, w: *Writer) Error!void {
    for (p.classes.items) |c| {
        if (c >= p.r.classes.len) continue;
        const crt = &p.r.classes[c];
        const def = crt.def.asPtrConst();
        var slot_names: std.ArrayList([]const u8) = .empty;
        for (def.layout_slots) |ls| try slot_names.append(p.a, ls.name);
        try writeNameList(w, "KCN", c, slot_names.items);
        try w.print("static const uint8_t KCS_{d}[] = {{", .{c});
        for (crt.seeds, 0..) |s, i| {
            if (i != 0) try w.writeAll(", ");
            try w.print("{d}", .{@intFromEnum(s)});
        }
        if (crt.seeds.len == 0) try w.writeAll("0");
        try w.writeAll("};\n");
        const anc = try ancestorsOf(p, c);
        try writeIds(w, "KCA", c, anc.ids);
        try writeNameList(w, "KCAN", c, anc.names);
        var prim: std.ArrayList([]const u8) = .empty;
        var prim_mut: std.ArrayList(u8) = .empty;
        for (def.primary_params) |pp| {
            try prim.append(p.a, pp.name);
            try prim_mut.append(p.a, if (pp.property) |mutable| @as(u8, if (mutable) 2 else 1) else 0);
        }
        try writeNameList(w, "KCP", c, prim.items);
        try w.print("static const uint8_t KCPM_{d}[] = {{", .{c});
        for (prim_mut.items, 0..) |x, i| {
            if (i != 0) try w.writeAll(", ");
            try w.print("{d}", .{x});
        }
        if (prim_mut.items.len == 0) try w.writeAll("0");
        try w.writeAll("};\n");
    }
    for (p.closures.items) |cc| {
        var anc: std.ArrayList(u32) = .empty;
        if (functionClass(p, cc.arity)) |f| {
            try anc.append(p.a, f);
            if (f < p.m.class_ancestors.items.len) for (p.m.class_ancestors.items[f]) |x| {
                if (x.int() != f) try anc.append(p.a, x.int());
            };
        }
        try writeIds(w, "KCA", cc.id, anc.items);
    }
    try w.print("static const klio_r_class KCLASSES[{d}] = {{\n", .{@max(p.classes.items.len + p.closures.items.len, 1)});
    var n: usize = 0;
    for (p.classes.items) |c| {
        if (c >= p.r.classes.len) continue;
        const crt = &p.r.classes[c];
        const def = crt.def.asPtrConst();
        const ic = &p.m.classes.items[c];
        const anc = try ancestorsOf(p, c);
        try w.print("  {{ {d}u, ", .{c});
        try ctype.writeCString(w, ic.name);
        try w.writeAll(", ");
        try ctype.writeCString(w, ic.fqn);
        try w.print(", {d}u, {d}u, KCN_{d}, KCS_{d}, {d}u, KCA_{d}, {d}u, KCAN_{d}, {d}u, KCP_{d}, KCPM_{d}, {d}u }},\n", .{
            classFlags(def), crt.seeds.len, c, c, anc.ids.len, c, anc.names.len, c, def.primary_params.len, c, c, crt.host_slot,
        });
        n += 1;
    }
    for (p.closures.items) |cc| {
        const fcls = functionClass(p, cc.arity);
        // A closure is the `FunctionN` of its arity to a type test and to
        // `::class`.
        const name, const fqn = if (fcls) |f| .{ p.m.classes.items[f].name, p.m.classes.items[f].fqn } else .{ "Function", "kotlin.Function" };
        var n_anc: usize = 0;
        if (fcls) |f| {
            n_anc = 1;
            if (f < p.m.class_ancestors.items.len) for (p.m.class_ancestors.items[f]) |x| {
                if (x.int() != f) n_anc += 1;
            };
        }
        try w.print("  {{ {d}u, ", .{cc.id});
        try ctype.writeCString(w, name);
        try w.writeAll(", ");
        try ctype.writeCString(w, fqn);
        try w.print(", {d}u, {d}u, 0, 0, {d}u, KCA_{d}, 0u, 0, 0u, 0, 0, {d}u }},\n", .{ rt.Flags.anonymous, cc.n_caps, n_anc, cc.id, NONE });
        n += 1;
    }
    if (n == 0) try w.writeAll("  { 0 }\n");
    try w.writeAll("};\n\n");
}

const Ancestors = struct { ids: []const u32, names: []const []const u8 };

/// Every supertype of `c` but `c`, with the names and FQNs the host's
/// by-name subtype tests read.
fn ancestorsOf(p: *Program, c: u32) Error!Ancestors {
    var ids: std.ArrayList(u32) = .empty;
    var names: std.ArrayList([]const u8) = .empty;
    if (c < p.m.class_ancestors.items.len) for (p.m.class_ancestors.items[c]) |x| {
        if (x.int() == c) continue;
        try ids.append(p.a, x.int());
        if (x.int() < p.m.classes.items.len) {
            const ac = &p.m.classes.items[x.int()];
            try names.append(p.a, ac.name);
            if (!std.mem.eql(u8, ac.fqn, ac.name)) try names.append(p.a, ac.fqn);
        }
    };
    return .{ .ids = ids.items, .names = names.items };
}

fn functionClass(p: *const Program, arity: u32) ?u32 {
    const fns = p.r.host_class.function;
    if (arity >= fns.len) return null;
    return fns[arity].int();
}

fn classFlags(def: anytype) u32 {
    const F = rt.Flags;
    var f: u32 = 0;
    if (def.is_data) f |= F.data;
    if (def.is_value) f |= F.value;
    if (def.is_object) f |= F.object;
    if (def.is_enum) f |= F.enum_;
    if (def.is_sealed) f |= F.sealed;
    if (def.is_interface) f |= F.interface;
    if (def.is_fun_interface) f |= F.fun_interface;
    if (def.is_open) f |= F.open;
    if (def.is_abstract) f |= F.abstract;
    if (def.is_inner) f |= F.inner;
    if (def.is_anonymous) f |= F.anonymous;
    if (def.is_annotation) f |= F.annotation;
    return f;
}

fn writeNameList(w: *Writer, comptime prefix: []const u8, id: u32, names: []const []const u8) Error!void {
    try w.print("static const char *const {s}_{d}[] = {{", .{ prefix, id });
    for (names, 0..) |s, i| {
        if (i != 0) try w.writeAll(", ");
        try ctype.writeCString(w, s);
    }
    if (names.len == 0) try w.writeAll("0");
    try w.writeAll("};\n");
}

fn writeIds(w: *Writer, comptime prefix: []const u8, id: u32, ids: []const u32) Error!void {
    try w.print("static const uint32_t {s}_{d}[] = {{", .{ prefix, id });
    for (ids, 0..) |x, i| {
        if (i != 0) try w.writeAll(", ");
        try w.print("{d}u", .{x});
    }
    if (ids.len == 0) try w.writeAll("0");
    try w.writeAll("};\n");
}

fn writeU32s(w: *Writer, name: []const u8, ids: []const u32) Error!void {
    try w.print("static const uint32_t {s}[] = {{", .{name});
    for (ids, 0..) |x, i| {
        if (i != 0) try w.writeAll(", ");
        try w.print("{d}u", .{x});
    }
    if (ids.len == 0) try w.writeAll("0");
    try w.writeAll("};\n");
}

fn optId(c: ?ClassId) u32 {
    return if (c) |x| x.int() else NONE;
}

fn optSlot(s: ?MethodSlotId) u32 {
    return if (s) |x| x.int() else NONE;
}

/// The natives, the callbacks and their dispatch, the host value kinds'
/// classes and the exceptions: what the runtime builds its module from.
fn writeProgram(p: *Program, w: *Writer, cbs: *const Callbacks) Error!void {
    // Natives, as the program numbers them.
    try w.print("static const klio_r_native KNATIVES[{d}] = {{\n", .{@max(p.rc.natives.items.len, 1)});
    for (p.rc.natives.items) |nid| {
        const n = p.r.natives[nid.int()];
        if (n.op != .none and n.op != .print_err) p.refuse("the compiler intrinsic `{s}`", .{n.name});
        var flags: u32 = 0;
        if (n.static_) flags |= 1;
        if (n.receiver) flags |= 2;
        try w.writeAll("  { ");
        try ctype.writeCString(w, n.name);
        try w.print(", {d}u, ", .{@as(u32, switch (n.table) {
            .natives => 0,
            .constructors => 1,
            .members => 2,
            .unbound => 3,
            // A fast path fronts a body the program compiles; it is never
            // one of the program's natives.
            .tries => 4,
        })});
        try ctype.writeCString(w, n.key);
        try w.print(", {d}u, {d}u, {d}, {d}u }},\n", .{
            flags, n.reified, if (n.vararg_back) |b| @as(i32, b) else -1, @intFromEnum(n.op),
        });
    }
    if (p.rc.natives.items.len == 0) try w.writeAll("  { 0 }\n");
    try w.writeAll("};\n");

    try w.print("static const klio_r_function KFUNCTIONS[{d}] = {{\n", .{@max(cbs.entries.items.len, 1)});
    for (cbs.entries.items, 0..) |cb, i| switch (cb) {
        .native => |n| try w.print("  {{ 0, {d}u, 0u }},\n", .{p.nativeIndex(n)}),
        .compiled => |f| try w.print("  {{ kw_{d}, 0u, {d}u }},\n", .{ i, p.body(f).?.sig.params.len }),
        .invoke => |arity| try w.print("  {{ kw_{d}, 0u, {d}u }},\n", .{ i, arity + 1 }),
        .closure => |c| try w.print("  {{ kw_{d}, 0u, {d}u }},\n", .{ i, @as(u32, if (c.which == .equals) 2 else 1) }),
    };
    if (cbs.entries.items.len == 0) try w.writeAll("  { 0 }\n");
    try w.writeAll("};\n");
    try w.print("static const klio_r_dispatch KDISPATCH[{d}] = {{\n", .{@max(cbs.dispatch.items.len, 1)});
    for (cbs.dispatch.items) |d| try w.print("  {{ {d}u, {d}u, {d}u }},\n", .{ d.cls, d.slot, d.entry });
    if (cbs.dispatch.items.len == 0) try w.writeAll("  { 0 }\n");
    try w.writeAll("};\n");
    var wks: std.ArrayList(u32) = .empty;
    for (p.r.well_known.values) |wk| try wks.append(p.a, optSlot(wk));
    try writeU32s(w, "KWELLKNOWN", wks.items);
    if (cbs.match_groups) |mg| {
        try w.print("static const klio_r_raised KMATCHGROUPS = {{ 0, {d}u, {d}u }};\n", .{ mg.class.int(), entryIndex(cbs, .{ .compiled = mg.ctor }) });
    } else try w.print("static const klio_r_raised KMATCHGROUPS = {{ 0, {d}u, {d}u }};\n", .{ NONE, NONE });
    try w.print("static const klio_r_raised KRAISED[{d}] = {{\n", .{cbs.fixed.len});
    for (cbs.fixed) |x| {
        if (x) |raised| {
            const entry = entryIndex(cbs, .{ .compiled = raised.ctor });
            try w.print("  {{ 0, {d}u, {d}u }},\n", .{ raised.class.int(), entry });
        } else try w.print("  {{ 0, {d}u, {d}u }},\n", .{ NONE, NONE });
    }
    try w.writeAll("};\n");
    try w.print("static const klio_r_raised KBYFQN[{d}] = {{\n", .{@max(cbs.by_fqn.items.len, 1)});
    for (cbs.by_fqn.items) |hr| {
        try w.writeAll("  { ");
        try ctype.writeCString(w, hr.fqn);
        try w.print(", {d}u, {d}u }},\n", .{ hr.raised.class.int(), entryIndex(cbs, .{ .compiled = hr.raised.ctor }) });
    }
    if (cbs.by_fqn.items.len == 0) try w.writeAll("  { 0 }\n");
    try w.writeAll("};\n");

    // The host value kinds' classes.
    const h = &p.r.host_class;
    const singles = [_]?ClassId{ h.unit, h.boolean, h.char, h.byte, h.short, h.int, h.long, h.float, h.double, h.ubyte, h.ushort, h.uint, h.ulong, h.string, h.array };
    var ids: std.ArrayList(u32) = .empty;
    for (singles) |c| try ids.append(p.a, optId(c));
    try writeU32s(w, "KH_SCALARS", ids.items);
    ids = .empty;
    for (h.by_tag) |c| try ids.append(p.a, optId(c));
    try writeU32s(w, "KH_TAGS", ids.items);
    ids = .empty;
    for (h.prim_array) |c| try ids.append(p.a, optId(c));
    try writeU32s(w, "KH_PRIM", ids.items);
    ids = .empty;
    for (h.range) |c| try ids.append(p.a, optId(c));
    try writeU32s(w, "KH_RANGE", ids.items);
    ids = .empty;
    for (h.progression) |c| try ids.append(p.a, optId(c));
    try writeU32s(w, "KH_PROG", ids.items);
    ids = .empty;
    for (h.function) |c| try ids.append(p.a, c.int());
    try writeU32s(w, "KH_FN", ids.items);
    ids = .empty;
    for (h.invoke_slot) |s| try ids.append(p.a, s.int());
    try writeU32s(w, "KH_INVOKE", ids.items);

    try w.writeAll("KLIO_NORETURN static void kthrow_hook(klio_value v) { kthrow(v); }\n");
    try w.print(
        \\static const klio_r_program KPROGRAM = {{
        \\  KCLASSES, {d}, KFUNCTIONS, {d}, KDISPATCH, {d}, KNATIVES, {d}, KWELLKNOWN, {d},
        \\  KRAISED, {d}, KBYFQN, {d},
        \\  KH_SCALARS, KH_TAGS, {d}, KH_PRIM, {d}, KH_RANGE, KH_PROG, {d}, KH_FN, {d}, KH_INVOKE, {d},
        \\  {d}u, {d}u, {d}u,
        \\  KMATCHGROUPS,
        \\  kthrow_hook,
        \\}};
        \\
        \\
    , .{
        p.classes.items.len + p.closures.items.len, cbs.entries.items.len, cbs.dispatch.items.len, p.rc.natives.items.len, p.r.well_known.values.len,
        cbs.fixed.len,                              cbs.by_fqn.items.len,
        h.by_tag.len,                               h.prim_array.len,   h.range.len,                 h.function.len,        h.invoke_slot.len,
        optSlot(h.equals_slot),                     optSlot(h.hash_code_slot), optSlot(h.to_string_slot),
    });
}

fn entryIndex(cbs: *const Callbacks, cb: Callback) u32 {
    for (cbs.entries.items, 0..) |e, i| {
        if (std.meta.eql(e, cb)) return @intCast(i);
    }
    return NONE;
}

fn writeMain(p: *Program, w: *Writer) Error!void {
    try w.writeAll("static void kmain(void) {\n  klio_try t; klio_try_arm(&t);\n  if (setjmp(t.jb) != 0) { klio_try_top = 0; klio_r_uncaught(klio_in_flight); }\n");
    const mb = p.body(p.main).?;
    if (p.unitIndex(p.mainUnit())) |ui| try w.print("  if (KU[{d}] != 2) ku_{d}();\n", .{ ui, ui });
    if (mb.sig.params.len == 0) {
        try w.print("  (void)kf_{d}();\n", .{p.main.int()});
    } else {
        const array = p.r.host_class.array orelse {
            p.refuse("`main` takes arguments, and the base declares no `Array`", .{});
            return;
        };
        try w.print("  KROOT[1] = klio_r_new_array({d}u, 0, 0);\n  (void)kf_{d}(KROOT[1]);\n", .{ array.int(), p.main.int() });
    }
    try w.writeAll("  klio_try_pop(&t);\n}\n\n");
    try w.print("int main(void) {{\n  if (klio_r_abi() != UINT64_C(0x{x})) {{ fputs(\"klio: this program was compiled for another klio runtime\\n\", stderr); return 2; }}\n", .{rt.abi});
    try w.writeAll("  klio_nat_init(0);\n  klio_r_describe(&KPROGRAM);\n");
    try w.writeAll("  for (unsigned i = 0; i < sizeof KROOT / sizeof KROOT[0]; i++) KROOT[i] = klio_nat_null();\n");
    for (p.statics.items, 0..) |st, i| {
        const t = sig_mod.seedTy(p.r.statics[st.int()].seed);
        if (t == .object) continue;
        try w.print("  KG[{d}] = ", .{i});
        try ctype.writeBox(w, t, "0");
        try w.writeAll(";\n");
    }
    try w.writeAll("  KROOTF.n = sizeof KROOT / sizeof KROOT[0]; KROOTF.slots = KROOT; klio_nat_enter(&KROOTF);\n");
    // The throwable in flight is rooted while a handler is found for it.
    try w.writeAll("  klio_in_flight = klio_nat_null();\n  static klio_nat_frame KIFF; KIFF.n = 1; KIFF.slots = &klio_in_flight; klio_nat_enter(&KIFF);\n");
    try w.writeAll("  return klio_r_run(kmain);\n}\n");
}
