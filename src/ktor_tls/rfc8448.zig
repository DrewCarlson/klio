fn hex(comptime s: []const u8) [s.len / 2]u8 {
    @setEvalBranchQuota(100_000);
    var out: [s.len / 2]u8 = undefined;
    for (&out, 0..) |*b, i| {
        b.* = (digit(s[2 * i]) << 4) | digit(s[2 * i + 1]);
    }
    return out;
}

fn digit(c: u8) u8 {
    return switch (c) {
        '0'...'9' => c - '0',
        'a'...'f' => c - 'a' + 10,
        else => unreachable,
    };
}

